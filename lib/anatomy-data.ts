// ==================== Types ====================
export type ZoomId = 'whole' | 'eyes' | 'nose' | 'mouth' | 'side' | 'neck' | 'throat' | 'posterior';

export interface FanGeometry {
  type: 'fan';
  n: number;
  bulge: number;
  A: readonly number[];
  B: readonly number[];
}

export interface RingGeometry {
  type: 'ring';
  n: number;
  cx: number;
  cy: number;
  rx: number;
  ry: number;
  irx: number;
  iry: number;
}

/** عضلة من جزأين أو أكثر (مثل digastric و omohyoid): كل جزء يُرسم كمروحة مستقلة. */
export interface MultiGeometry {
  type: 'multi';
  parts: readonly FanGeometry[];
}

export type Geometry = FanGeometry | RingGeometry | MultiGeometry;

export interface Muscle {
  id: string;
  paired: boolean;
  zoom: ZoomId;
  geometry: Geometry;
  en: string;
  short?: string;
  label: { s: 'L' | 'R'; x: number; y: number };
  nerve: string;
  origin: string;
  insertion: string;
  actEn: string;
  clin: string;
  arrows: readonly (readonly [number, number, number, number])[];
  pose: Record<string, number>;
  region?: string;
}

